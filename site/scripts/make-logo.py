#!/usr/bin/env python3
"""Draw the DiskGOup logo for the documentation site.

The site shows the app's own icon — the donut chart on the dark squircle.
This script draws that icon as vector art and writes it twice: once for the
Starlight header and once for the browser tab.

    python3 site/scripts/make-logo.py

The geometry, the palette and the segment sizes are the same as
`electron/scripts/make-icon.py`, which draws the raster app icon, so the two
never drift apart. Run this after the app icon changes.

Needs nothing but the standard library.
"""

from __future__ import annotations

import math
import os

SIZE = 512
CX = CY = SIZE / 2

# The app's own palette (see ui/src/styles.css and electron/scripts/make-icon.py).
BG_TOP = "#161b22"
BG_BOTTOM = "#0d1117"
SEGMENTS = [(55, "#58a6ff"), (28, "#5ac18e"), (17, "#f5a623")]

# The donut, as a share of the canvas.
OUTER = SIZE * 0.355
INNER = OUTER * 0.52
GAP = 2.5  # degrees between the segments

# The macOS superellipse exponent.
N = 5

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def squircle_path(steps: int = 180) -> str:
    """The macOS superellipse |x|^5 + |y|^5 = 1, as a polygon path."""
    points = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        x = math.copysign(abs(c) ** (2 / N), c)
        y = math.copysign(abs(s) ** (2 / N), s)
        points.append((CX + x * CX, CY + y * CY))
    parts = [f"M {points[0][0]:.2f} {points[0][1]:.2f}"]
    parts += [f"L {x:.2f} {y:.2f}" for x, y in points[1:]]
    parts.append("Z")
    return " ".join(parts)


def point(radius: float, angle: float) -> tuple[float, float]:
    """A point on a circle, in degrees, clockwise from three o'clock."""
    rad = math.radians(angle)
    return CX + radius * math.cos(rad), CY + radius * math.sin(rad)


def segment_path(a1: float, a2: float) -> str:
    """An annular sector — the pie slice minus the hole in the middle."""
    large = 1 if (a2 - a1) > 180 else 0
    x1, y1 = point(OUTER, a1)
    x2, y2 = point(OUTER, a2)
    x3, y3 = point(INNER, a2)
    x4, y4 = point(INNER, a1)
    return (
        f"M {x1:.2f} {y1:.2f} "
        f"A {OUTER:.2f} {OUTER:.2f} 0 {large} 1 {x2:.2f} {y2:.2f} "
        f"L {x3:.2f} {y3:.2f} "
        f"A {INNER:.2f} {INNER:.2f} 0 {large} 0 {x4:.2f} {y4:.2f} Z"
    )


def build() -> str:
    """The logo as an SVG document."""
    paths = []
    start = -90.0
    for share, color in SEGMENTS:
        sweep = 360.0 * share / 100.0
        paths.append(f'    <path d="{segment_path(start + GAP, start + sweep - GAP)}" fill="{color}"/>')
        start += sweep
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" '
        'width="{size}" height="{size}" role="img" aria-label="DiskGOup">\n'
        "  <!-- The DiskGOup app icon: a donut chart on the app's dark squircle.\n"
        "       Generated by site/scripts/make-logo.py — the same geometry as\n"
        "       electron/scripts/make-icon.py, which draws the raster app icon. -->\n"
        "  <defs>\n"
        '    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">\n'
        f'      <stop offset="0" stop-color="{BG_TOP}"/>\n'
        f'      <stop offset="1" stop-color="{BG_BOTTOM}"/>\n'
        "    </linearGradient>\n"
        '    <clipPath id="squircle">\n'
        f'      <path d="{squircle_path()}"/>\n'
        "    </clipPath>\n"
        "  </defs>\n"
        '  <g clip-path="url(#squircle)">\n'
        f'    <rect width="{SIZE}" height="{SIZE}" fill="url(#bg)"/>\n'
        "{segments}\n"
        "  </g>\n"
        "</svg>\n"
    ).format(size=SIZE, segments="\n".join(paths))


def main() -> int:
    svg = build()
    for path in (
        os.path.join(ROOT, "src", "assets", "logo.svg"),
        os.path.join(ROOT, "public", "favicon.svg"),
    ):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(svg)
        print(f"✓ {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
