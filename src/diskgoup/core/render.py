"""SVG rendering for the spatial views.

The CLI writes standalone SVG files; the Electron renderer draws the same
geometry itself from the JSON layout. Keeping the geometry in the CLI means the
GUI never has to know how a treemap is laid out.
"""

from __future__ import annotations

import math
from xml.sax.saxutils import escape

from diskgoup.core.views import LayoutNode

#: DiskBOX-style dark palette, keyed by file kind.
KIND_COLORS: dict[str, str] = {
    "game": "#e056a0",
    "video": "#ef6461",
    "archive": "#f5a623",
    "document": "#4ab3c4",
    "cache": "#5ac18e",
    "application": "#5b8dee",
    "audio": "#c678dd",
    "image": "#56b6c2",
    "code": "#7f848e",
    "system": "#5c6370",
    "other": "#8b93a7",
}

#: Accent used for the headline and interactive affordances.
ACCENT = "#f5a623"

BACKGROUND = "#0d1117"
PANEL = "#161b22"
BORDER = "#30363d"
TEXT = "#e6edf3"
TEXT_DIM = "#8b949e"


def color_for(node: LayoutNode) -> str:
    """The fill colour for a node."""
    kind = node.color_kind or node.kind
    return KIND_COLORS.get(kind, KIND_COLORS["other"])


def _header(title: str, width: float, height: float) -> list[str]:
    return [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width:g}" height="{height:g}" '
        f'viewBox="0 0 {width:g} {height:g}" '
        f'font-family="Inter, Segoe UI, system-ui, sans-serif">',
        f'<rect width="{width:g}" height="{height:g}" fill="{BACKGROUND}"/>',
        f'<text x="16" y="28" fill="{TEXT}" font-size="16" font-weight="600">'
        f"{escape(title)}</text>",
    ]


def _footer(width: float, height: float) -> list[str]:
    return [
        f'<text x="16" y="{height - 12:g}" fill="{TEXT_DIM}" font-size="11">'
        "Generated by DiskGOup</text>",
        "</svg>",
    ]


def render_treemap(
    nodes: list[LayoutNode],
    *,
    width: float = 1200.0,
    height: float = 800.0,
    title: str = "Disk storage",
) -> str:
    """Render squarified treemap tiles."""
    parts = _header(title, width, height)
    for node in nodes:
        rect = node.rect
        if rect is None or rect.width <= 0 or rect.height <= 0:
            continue
        fill = color_for(node)
        parts.append(
            f'<g class="node" data-path="{escape(node.path)}">'
            f"<title>{escape(node.name)}</title>"
            f'<rect x="{rect.x:g}" y="{rect.y:g}" width="{rect.width:g}" '
            f'height="{rect.height:g}" fill="{fill}" fill-opacity="0.85" '
            f'stroke="{BACKGROUND}" stroke-width="2"/>'
        )
        if rect.width > 70 and rect.height > 26:
            label = escape(_truncate(node.name, int(rect.width / 8)))
            parts.append(
                f'<text x="{rect.x + 8:g}" y="{rect.y + 20:g}" fill="#0d1117" '
                f'font-size="13" font-weight="600">{label}</text>'
            )
        if rect.width > 70 and rect.height > 44:
            value = escape(_truncate(_bytes(node.size), int(rect.width / 8)))
            parts.append(
                f'<text x="{rect.x + 8:g}" y="{rect.y + 38:g}" fill="#0d1117" '
                f'font-size="11">{value}</text>'
            )
        parts.append("</g>")
    parts.extend(_footer(width, height))
    return "".join(parts)


def render_sunburst(
    nodes: list[LayoutNode],
    *,
    width: float = 1200.0,
    height: float = 800.0,
    title: str = "Disk storage",
) -> str:
    """Render radial arcs."""
    parts = _header(title, width, height)
    cx, cy = width / 2, height / 2
    outer = min(width, height) * 0.46

    max_radius = max((node.radius for node in nodes), default=1)
    ring = outer / max(1, max_radius)

    parts.append(
        f'<circle cx="{cx:g}" cy="{cy:g}" r="{ring * 0.9:g}" fill="{PANEL}" stroke="{BORDER}"/>'
    )
    for node in nodes:
        if node.radius <= 0:
            continue
        inner = ring * (node.radius - 1)
        outer_r = ring * node.radius
        path = _arc_path(cx, cy, inner, outer_r, node.start_angle, node.end_angle)
        if not path:
            continue
        parts.append(
            f'<path d="{path}" fill="{color_for(node)}" fill-opacity="0.88" '
            f'stroke="{BACKGROUND}" stroke-width="1.5" data-path="{escape(node.path)}">'
            f"<title>{escape(node.name)}</title></path>"
        )
    parts.extend(_footer(width, height))
    return "".join(parts)


def render_flame(
    nodes: list[LayoutNode],
    *,
    width: float = 1200.0,
    height: float = 800.0,
    title: str = "Disk storage",
) -> str:
    """Render an icicle / flame graph."""
    parts = _header(title, width, height)
    max_depth = max((node.depth for node in nodes), default=0)
    row_height = min(34.0, max(20.0, (height - 60) / max(1, max_depth + 1)))
    total = max((node.radius for node in nodes), default=1) or 1
    scale = (width - 32) / total

    for node in nodes:
        width_px = node.radius * scale
        if width_px <= 0:
            continue
        parts.append(
            f'<g data-path="{escape(node.path)}">'
            f"<title>{escape(node.name)}</title>"
            f'<rect x="{16 + node.x * scale:g}" y="{40 + node.y:g}" width="{width_px:g}" '
            f'height="{row_height - 2:g}" fill="{color_for(node)}" fill-opacity="0.85" '
            f'stroke="{BACKGROUND}" stroke-width="1"/>'
        )
        if width_px > 60:
            parts.append(
                f'<text x="{24 + node.x * scale:g}" y="{40 + node.y + row_height - 12:g}" '
                f'fill="#0d1117" font-size="11" font-weight="600">'
                f"{escape(_truncate(node.name, int(width_px / 7)))}</text>"
            )
        parts.append("</g>")
    parts.extend(_footer(width, height))
    return "".join(parts)


def render_bubbles(
    nodes: list[LayoutNode],
    *,
    width: float = 1200.0,
    height: float = 800.0,
    title: str = "Disk storage",
) -> str:
    """Render packed circles."""
    parts = _header(title, width, height)
    for node in nodes:
        radius = node.radius
        if radius <= 0:
            continue
        parts.append(
            f'<circle cx="{node.x:g}" cy="{node.y:g}" r="{radius:g}" '
            f'fill="{color_for(node)}" fill-opacity="0.72" stroke="{BACKGROUND}" '
            f'stroke-width="2" data-path="{escape(node.path)}">'
            f"<title>{escape(node.name)} — {escape(_bytes(node.size))}</title></circle>"
        )
        if radius > 34:
            parts.append(
                f'<text x="{node.x:g}" y="{node.y:g}" fill="#0d1117" font-size="12" '
                f'font-weight="600" text-anchor="middle">{escape(_truncate(node.name, 16))}</text>'
            )
    parts.extend(_footer(width, height))
    return "".join(parts)


def render_mindmap(
    nodes: list[LayoutNode],
    *,
    width: float = 1200.0,
    height: float = 800.0,
    title: str = "Disk storage",
) -> str:
    """Render a radial hub with straight links."""
    parts = _header(title, width, height)

    # Links first, so the nodes paint on top of them.
    by_path = {node.path: node for node in nodes}
    for node in nodes:
        parent = by_path.get(node.parent_path) if node.parent_path else None
        if parent is None:
            continue
        parts.append(
            f'<line x1="{parent.x:g}" y1="{parent.y:g}" x2="{node.x:g}" y2="{node.y:g}" '
            f'stroke="#4b5563" stroke-width="2"/>'
        )

    for node in nodes:
        radius = node.radius if node.radius > 0 else 8
        parts.append(
            f'<circle cx="{node.x:g}" cy="{node.y:g}" r="{min(radius, 26):g}" '
            f'fill="{color_for(node)}" fill-opacity="0.9" stroke="{BACKGROUND}" '
            f'stroke-width="2" data-path="{escape(node.path)}">'
            f"<title>{escape(node.name)} — {escape(_bytes(node.size))}</title></circle>"
        )
        if radius > 20:
            parts.append(
                f'<text x="{node.x:g}" y="{node.y + radius + 16:g}" fill="{TEXT_DIM}" '
                f'font-size="11" text-anchor="middle">'
                f"{escape(_truncate(node.name, 20))}</text>"
            )
    parts.extend(_footer(width, height))
    return "".join(parts)


def _arc_path(cx: float, cy: float, inner: float, outer: float, start: float, end: float) -> str:
    """SVG path for an annular sector.

    The innermost ring has no hole, so it is drawn as a pie wedge instead — an
    arc with a zero radius is not valid SVG.
    """
    if outer <= 0 or end <= start:
        return ""
    large_arc = 1 if (end - start) > math.pi else 0
    x0 = cx + outer * math.cos(start)
    y0 = cy + outer * math.sin(start)
    x1 = cx + outer * math.cos(end)
    y1 = cy + outer * math.sin(end)

    if inner <= 0:
        return (
            f"M {cx:g} {cy:g} L {x0:g} {y0:g} A {outer:g} {outer:g} 0 {large_arc} 1 {x1:g} {y1:g} Z"
        )

    x2 = cx + inner * math.cos(end)
    y2 = cy + inner * math.sin(end)
    x3 = cx + inner * math.cos(start)
    y3 = cy + inner * math.sin(start)
    return (
        f"M {x0:g} {y0:g} "
        f"A {outer:g} {outer:g} 0 {large_arc} 1 {x1:g} {y1:g} "
        f"L {x2:g} {y2:g} "
        f"A {inner:g} {inner:g} 0 {large_arc} 0 {x3:g} {y3:g} Z"
    )


def _truncate(text: str, limit: int) -> str:
    if limit <= 1 or len(text) <= limit:
        return text
    return text[: max(1, limit - 1)] + "…"


def _bytes(size: int) -> str:
    value = float(size)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if value < 1024 or unit == "TB":
            precision = 0 if value >= 10 or unit == "B" else 1
            return f"{value:.{precision}f} {unit}"
        value /= 1024
    return f"{size} B"
